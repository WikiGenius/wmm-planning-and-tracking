%% setup_project.m
% One-shot bootstrapper for the mobile manipulator MATLAB framework.
% Builds folders, writes starter files, and runs Step 1 test automatically.

function setup_project()
clc; close all;

%% ────────────────────────────────
%  Define root + subfolders
% ────────────────────────────────
root = fullfile(pwd, 'wheeled_manipulator_framework');
dirs = { ...
  'docs/figures', ...
  'docs/derivations', ...
  'params', ...
  'models/base', ...
  'models/arm', ...
  'models/coupled', ...
  'control', ...
  'sim/integrators', ...
  'sim/plants', ...
  'sim/scenarios', ...
  'sim/logs', ...
  'viz', ...
  'tests' ...
};

fprintf('📦 Creating project at: %s\n', root);
for i = 1:numel(dirs)
  p = fullfile(root, dirs{i});
  if ~exist(p, 'dir'), mkdir(p); end
end

%% ────────────────────────────────
%  Helper: write file safely
% ────────────────────────────────
function write_file(path, content, overwrite)
  if nargin < 3, overwrite = false; end
  % nested helper for nice display
  function s = relpath(p)
    s = strrep(p, [root filesep], '');
  end

  if exist(path, 'file') && ~overwrite
    fprintf('   ↪︎ exists, skip: %s\n', relpath(path));
    return;
  end

  fid = fopen(path, 'w');
  if fid < 0, error('Cannot open %s', path); end

  % normalize content → char
  if isstring(content)
    content = strjoin(content, newline);
  elseif iscell(content)
    content = strjoin(content, '');
  end
  if ~ischar(content)
    content = char(content);
  end

  fprintf(fid, '%s', content);
  fclose(fid);
  fprintf('   ✓ wrote: %s\n', relpath(path));
end

%% ────────────────────────────────
%  1. README
% ────────────────────────────────
write_file(fullfile(root,'README.md'), ...
['# mobile\_manipulator\_matlab' newline ...
'Starter MATLAB scaffold for a coupled mobile manipulator ' ...
'(differential-drive base + 3R arm).' newline newline ...
'Run Step 1 test:' newline newline ...
'```matlab' newline ...
'cd wheeled_manipulator_framework/tests' newline ...
'run(''test_base_kin.m'')' newline ...
'```' newline], false);

%% ────────────────────────────────
%  2. PARAMS
% ────────────────────────────────
write_file(fullfile(root,'params','mm_physical.m'), ...
['function P = mm_physical()' newline ...
'%MM_PHYSICAL  Physical parameters (from paper Table 2).' newline ...
'P.base.L  = 0.250;   % [m] half-track' newline ...
'P.base.r  = 0.075;   % [m] wheel radius' newline ...
'P.base.m  = 19.2372; % [kg]' newline ...
'P.base.Iz = 0.7004;  % [kg*m^2]' newline newline ...
'P.wheel.m  = 0.901;' newline ...
'P.wheel.Iy = 0.0015; P.wheel.Iz = 0.0030;' newline newline ...
'P.arm.L0 = 0.325; P.arm.L1 = 0.200; P.arm.L2 = 0.300; P.arm.L3 = 0.300;' newline ...
'P.arm.m  = [3.293, 3.436, 1.229];' newline ...
'P.arm.Lcmx = [0.167, 0.246, 0.150];' newline ...
'P.arm.Ixx = [0.0053, 0.0054, 0.0017];' newline ...
'P.arm.Iyy = [0.0221, 0.0457, 0.0242];' newline ...
'P.arm.Izz = [0.0230, 0.0461, 0.0255];' newline ...
'end' newline]);

write_file(fullfile(root,'params','sim_cfg.m'), ...
['function cfg = sim_cfg()' newline ...
'cfg.h = 0.002;' newline ...
'cfg.T = 2.0;' newline ...
'cfg.N = round(cfg.T/cfg.h);' newline ...
'cfg.integrator = ''rk4'';' newline ...
'end' newline]);

write_file(fullfile(root,'params','arm_dh.m'), ...
['function DH = arm_dh()' newline ...
'%ARM_DH  Minimal DH table for a 3R arm (placeholder).' newline ...
'% [a, alpha, d, theta]' newline ...
'DH = [0, pi/2, 0, 0;' newline ...
'      0.2, 0, 0, 0;' newline ...
'      0.3, 0, 0, 0];' newline ...
'end' newline]);

%% ────────────────────────────────
%  3. MODELS: Base kinematics
% ────────────────────────────────
write_file(fullfile(root,'models','base','base_kin_fwd.m'), ...
['function [v,omega] = base_kin_fwd(wR,wL,P)' newline ...
'%BASE_KIN_FWD  Differential-drive forward velocity map.' newline ...
'r = P.base.r; L = P.base.L;' newline ...
'v     = (r/2) * (wR + wL);' newline ...
'omega = (r/(2*L)) * (wR - wL);' newline ...
'end' newline]);

write_file(fullfile(root,'models','base','base_kin_inv.m'), ...
['function [wR,wL] = base_kin_inv(v,omega,P)' newline ...
'%BASE_KIN_INV  Inverse velocity map.' newline ...
'r = P.base.r; L = P.base.L;' newline ...
'wR = (1/r) * (v + L*omega);' newline ...
'wL = (1/r) * (v - L*omega);' newline ...
'end' newline]);

%% ────────────────────────────────
%  4. SIM: Integrators + plant
% ────────────────────────────────
write_file(fullfile(root,'sim','integrators','step_euler.m'), ...
['function xnext = step_euler(f,t,x,u,h,P)' newline ...
'xdot = f(t,x,u,P);' newline ...
'xnext = x + h*xdot;' newline ...
'end' newline]);

write_file(fullfile(root,'sim','integrators','step_rk4.m'), ...
['function xnext = step_rk4(f,t,x,u,h,P)' newline ...
'k1 = f(t,        x,           u,P);' newline ...
'k2 = f(t + h/2,  x + h*k1/2,  u,P);' newline ...
'k3 = f(t + h/2,  x + h*k2/2,  u,P);' newline ...
'k4 = f(t + h,    x + h*k3,    u,P);' newline ...
'xnext = x + (h/6)*(k1 + 2*k2 + 2*k3 + k4);' newline ...
'end' newline]);

write_file(fullfile(root,'sim','plants','mm_plant.m'), ...
['function xdot = mm_plant(~,x,u,P)' newline ...
'%MM_PLANT  Minimal kinematic plant for smoke tests (no arm yet).' newline ...
'xpos = x(1); ypos = x(2); phi = x(3);' newline ...
'v = u.v; omega = u.omega;' newline ...
'x_dot = v*cos(phi); y_dot = v*sin(phi); phi_dot = omega;' newline ...
'xdot = zeros(12,1);' newline ...
'xdot(1)=x_dot; xdot(2)=y_dot; xdot(3)=phi_dot;' newline ...
'end' newline]);

write_file(fullfile(root,'sim','scenarios','scen_joint_steps.m'), ...
['function ref = scen_joint_steps()' newline ...
'ref.v = @(t) 0.2*(t<5) + 0.0*(t>=5);' newline ...
'ref.omega = @(t) 0.0;' newline ...
'ref.q = @(t) [0;0;0];' newline ...
'end' newline]);

write_file(fullfile(root,'sim','run_sim.m'), ...
['clear; clc; addpath(genpath(''.''));' newline ...
'P = mm_physical(); cfg = sim_cfg();' newline ...
'x = zeros(12,1); t = 0; T = t; X = x.'';' newline ...
'ref = scen_joint_steps();' newline ...
'f  = @(tt,xx,uu,PP) mm_plant(tt,xx,uu,PP);' newline ...
'if cfg.integrator==''rk4'', step=@step_rk4; else, step=@step_euler; end' newline ...
'for k=1:cfg.N' newline ...
'  v_cmd  = ref.v(t);  om_cmd = ref.omega(t);' newline ...
'  u = struct(''v'',v_cmd,''omega'',om_cmd);' newline ...
'  x = step(f,t,x,u,cfg.h,P);' newline ...
'  t = t + cfg.h; T(end+1,1)=t; X(end+1,:)=x.'';' newline ...
'end' newline ...
'figure; subplot(3,1,1); plot(T,X(:,1)); ylabel(''x [m]'');' newline ...
'subplot(3,1,2); plot(T,X(:,2)); ylabel(''y [m]'');' newline ...
'subplot(3,1,3); plot(T,X(:,3)); ylabel(''\phi [rad]''); xlabel(''t [s]'');' newline ...
'end' newline]);

%% ────────────────────────────────
%  5. VIZ helper
% ────────────────────────────────
write_file(fullfile(root,'viz','plot_timeseries.m'), ...
['function plot_timeseries(T,X)' newline ...
'figure; subplot(3,1,1); plot(T,X(:,1:2)); ylabel(''[x y]'');' newline ...
'subplot(3,1,2); plot(T,X(:,3)); ylabel(''\phi'');' newline ...
'subplot(3,1,3); plot(T,X(:,4:6)); ylabel(''q''); xlabel(''t'');' newline ...
'end' newline]);

%% ────────────────────────────────
%  6. TESTS: Step 1 base kinematics
% ────────────────────────────────
write_file(fullfile(root,'tests','test_base_kin.m'), ...
['function test_base_kin()' newline ...
'%TEST_BASE_KIN  Unit test for base_kin_fwd / base_kin_inv.' newline ...
'clear; clc;' newline ...
'' newline ...
'% Add parent folder (project root) to path so MATLAB finds models/params' newline ...
'thisDir = fileparts(mfilename(''fullpath''));' newline ...
'addpath(genpath(fullfile(thisDir, ''..'')));' newline ...
'' newline ...
'% Load parameters' newline ...
'P = mm_physical();' newline ...
'tol = 1e-12;' newline ...
'' newline ...
'% --- A) Straight motion (equal wheel speeds) ---' newline ...
'wR = 10; wL = 10;' newline ...
'[v,om] = base_kin_fwd(wR,wL,P);' newline ...
'assert(abs(v - P.base.r*10) < tol);' newline ...
'assert(abs(om) < tol);' newline ...
'' newline ...
'% --- B) Spin in place (opposite wheels) ---' newline ...
'wR = 10; wL = -10;' newline ...
'[v,om] = base_kin_fwd(wR,wL,P);' newline ...
'assert(abs(v) < tol);' newline ...
'assert(abs(om - (10*P.base.r/P.base.L)) < tol);' newline ...
'' newline ...
'% --- C) Round-trip inverse check ---' newline ...
'v0 = 0.35; om0 = 0.8;' newline ...
'[wR,wL] = base_kin_inv(v0,om0,P);' newline ...
'[v1,om1] = base_kin_fwd(wR,wL,P);' newline ...
'assert(abs(v1-v0) < 1e-12);' newline ...
'assert(abs(om1-om0) < 1e-12);' newline ...
'' newline ...
'disp(''✅ base_kin_fwd / base_kin_inv tests passed.'');' newline ...
'end' newline]);

%% ────────────────────────────────
%  7. Run Step 1 test automatically
% ────────────────────────────────
fprintf('\n🚀 Project scaffold created.\n');
fprintf('\n🧪 Running Step 1 test...\n');

origDir = pwd;
cd(fullfile(root,'tests'));
try
    test_base_kin();   % call the function
catch ME
    cd(origDir);
    rethrow(ME);
end
cd(origDir);
fprintf('\n✅ Setup complete. Ready for Step 2 (constraints A(q), R(q)).\n');
end
